const { app, BrowserWindow, dialog } = require('electron')
const { mkdtempSync, readFileSync, realpathSync, rmSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const assert = require('node:assert/strict')

const directory = mkdtempSync(join(tmpdir(), 'sql-connect-ui-'))
app.setPath('userData', directory)
const root = resolve(process.env.SQL_CONNECT_TEST_APP_ROOT || '.')
app.getAppPath = () => root
let savePath = join(directory, '中文新数据库.sqlite')
let openPath
dialog.showSaveDialog = async () => ({ canceled: !savePath, filePath: savePath })
dialog.showOpenDialog = async () => openPath ? ({ canceled: false, filePaths: [openPath] }) : ({ canceled: true, filePaths: [] })
require(join(root, 'out/main/index.js'))

const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
async function until(fn, description) {
  for (let i = 0; i < 150; i++) { if (await fn()) return; await delay(100) }
  throw new Error(`Timed out: ${description}`)
}
async function press(window, keyCode, modifiers = []) {
  await window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers })
  await window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers })
}
app.whenReady().then(async () => {
  let exitCode = 0
  try {
    await until(() => BrowserWindow.getAllWindows().length > 0, 'window created')
    const window = BrowserWindow.getAllWindows()[0]
    const js = code => window.webContents.executeJavaScript(code)
    await until(() => js('!!document.querySelector(".welcome-actions")'), 'renderer mounted')
    assert.equal(await js('document.querySelector(".sidebar-head h2")?.textContent'), '新建连接')
    assert.equal(await js('!!document.querySelector(".quick-actions")'), false)
    await js('document.querySelector(".connection-menu-button").click()')
    assert.equal(await js('document.querySelector(".connection-menu")?.textContent.includes("SQLite")'), true)
    assert.equal(await js('document.querySelector(".connection-menu")?.textContent.includes("MySQL")'), true)
    await until(() => js('document.activeElement?.dataset.connectionOption === "sqlite"'), 'connection menu focuses SQLite')
    await js('document.dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true }))')
    assert.equal(await js('document.activeElement?.dataset.connectionOption'), 'mysql')
    await js('document.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", bubbles: true }))')
    await until(() => js('!!document.querySelector(".modal-card")'), 'MySQL connection form opens')
    assert.equal(await js('document.querySelector(".modal-card")?.textContent.includes("连接 MySQL")'), true)
    await js('document.querySelector(".modal-card .secondary-btn")?.click()')
    assert.equal(await js('!!document.querySelector(".modal-card")'), false)
    console.log('PASS: MySQL connection form opens, exposes TLS/password options, and cancels')
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    assert.equal(await js('document.querySelector("[data-connection-option=sqlite-create]")?.textContent'), '新建 SQLite')
    assert.equal(await js('document.querySelector("[data-connection-option=sqlite-open]")?.textContent'), '打开 SQLite')
    await js('document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }))')
    assert.equal(await js('!!document.querySelector(".connection-menu")'), false)
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    await js('document.querySelector("[data-connection-option=sqlite-open]").click()')
    assert.equal(await js('!!document.querySelector(".connection-menu")'), false)
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    const create = () => js('document.querySelector("[data-connection-option=sqlite-create]").click()')
    await create()
    await until(() => js('document.querySelector(".connection-row")?.textContent.includes("在线") && !document.querySelector(".statusbar").textContent.includes("正在执行")'), 'create completes in UI')
    let connections = JSON.parse(readFileSync(join(directory, 'connections.json'), 'utf8'))
    assert.equal(connections.length, 1)
    assert.equal(connections[0].path, realpathSync(savePath))
    console.log('PASS: UI new database button → worker → saved connection → ready status')
    openPath = savePath
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    await js('document.querySelector("[data-connection-option=sqlite-open]").click()')
    await until(() => js('document.querySelectorAll(".connection-row").length === 1 && document.querySelector(".toast.info")?.textContent.includes("已复用现有连接")'), 'duplicate SQLite reuses existing connection')
    console.log('PASS: opening the same SQLite file reuses the existing connection')
    const newSqlTabs = count => js('Array.from({ length: ' + count + ' }, () => document.querySelector(".new-query").click())')
    const openMenuAt = index => js('(() => { const tab = document.querySelectorAll(".tab")[' + index + ']; tab.dispatchEvent(new MouseEvent("contextmenu", { bubbles: true, clientX: 120, clientY: 120 })); return document.querySelector(".tab.active") === tab; })()')
    await newSqlTabs(5)
    const activeBeforeMenu = await js('document.querySelector(".tab.active")?.textContent')
    assert.equal(await openMenuAt(2), false)
    assert.equal(await js('document.querySelector(".tab-context-menu")?.textContent'), '关闭左侧窗口关闭右侧窗口关闭其他窗口')
    assert.equal(await js('document.querySelectorAll(".tab-context-menu button")[0].disabled'), false)
    await js('document.querySelectorAll(".tab-context-menu button")[0].click()')
    assert.equal(await js('document.querySelectorAll(".tab").length'), 3)
    assert.equal(await js('document.querySelector(".tab.active")?.textContent'), activeBeforeMenu)
    await newSqlTabs(2)
    await openMenuAt(2)
    await js('document.querySelectorAll(".tab-context-menu button")[1].click()')
    assert.equal(await js('document.querySelectorAll(".tab").length'), 3)
    await newSqlTabs(3)
    await openMenuAt(2)
    await js('document.querySelectorAll(".tab-context-menu button")[2].click()')
    assert.equal(await js('document.querySelectorAll(".tab").length'), 1)
    await newSqlTabs(2)
    await openMenuAt(0)
    await js('document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }))')
    assert.equal(await js('!!document.querySelector(".tab-context-menu")'), false)
    console.log('PASS: tab context menu left/right/others, inactive target, Escape dismissal')
    await js('document.querySelector(".new-query").click()')
    await until(() => js('!!document.querySelector(".cm-content")'), 'SQL editor opened')
    await js('document.querySelector(".cm-content").focus()')
    await window.webContents.insertText('sel')
    await until(() => js('document.querySelector(".cm-tooltip-autocomplete")?.textContent.includes("SELECT")'), 'SQL keyword completion appears')
    await delay(150)
    await press(window, 'Tab')
    await until(() => js('document.querySelector(".cm-content")?.innerText.trim() === "SELECT"'), 'Tab accepts SQL completion')
    await js('document.querySelector(".new-query").click()')
    await until(() => js('document.querySelector(".cm-content")?.innerText.trim() === ""'), 'new SQL editor is empty')
    await js('document.querySelector(".cm-content").focus()')
    await window.webContents.insertText('x')
    await press(window, 'ENTER')
    await press(window, 'Tab')
    assert.equal(await js('/\\n\\s+$/.test(document.querySelector(".cm-content")?.innerText || "")'), true)
    await js('document.execCommand("selectAll")')
    await window.webContents.insertText('SELECT 1')
    const sqlBeforeShortcut = await js('document.querySelector(".cm-content")?.innerText')
    await press(window, 'ENTER', ['meta'])
    await until(() => js('Array.from(document.querySelectorAll(".result-table td")).some(cell => cell.textContent.trim() === "1")'), 'Command-Enter executes SQL')
    assert.equal(sqlBeforeShortcut.includes('\n'), false)
    console.log('PASS: SQL keyword completion with Tab and Command-Enter execution')
    savePath = join(directory, 'missing-directory', 'fail.sqlite')
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    await create()
    await until(() => js('!!document.querySelector(".toast.error") && !document.querySelector(".statusbar").textContent.includes("正在执行")'), 'invalid path clears loading')
    console.log('PASS: UI reports creation error and clears loading')
    savePath = join(directory, 'retry.sqlite')
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    await create()
    await until(() => js('document.querySelectorAll(".connection-row").length === 2 && !document.querySelector(".statusbar").textContent.includes("正在执行")'), 'retry succeeds')
    savePath = join(directory, 'disconnect-target.sqlite')
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    await create()
    await until(() => js('document.querySelectorAll(".connection-row").length === 3 && Array.from(document.querySelectorAll(".connection-row")).some(row => row.textContent.includes("disconnect-target") && row.textContent.includes("在线"))'), 'third connection ready')
    await js('(() => { const block = Array.from(document.querySelectorAll(".connection-block")).find(item => item.textContent.includes("disconnect-target")); block.querySelector(".disconnect-control").click() })()')
    await until(() => js('Array.from(document.querySelectorAll(".connection-block")).some(item => item.textContent.includes("disconnect-target") && !item.textContent.includes("在线"))'), 'target connection disconnects')
    assert.equal(await js('document.querySelectorAll(".connection-row").length'), 3)
    assert.equal(await js('!!document.querySelector(".sidebar-footer")'), false)
    assert.equal(await js('Array.from(document.querySelectorAll(".connection-block")).filter(item => item.textContent.includes("在线")).length'), 2)
    await js('Array.from(document.querySelectorAll(".connection-block")).find(item => item.textContent.includes("disconnect-target")).querySelector(".connection-main").click()')
    await until(() => js('Array.from(document.querySelectorAll(".connection-block")).some(item => item.textContent.includes("disconnect-target") && item.textContent.includes("在线"))'), 'target connection reconnects')
    console.log('PASS: per-connection disconnect icon only disconnects and reconnects the selected row')
    savePath = undefined
    await js('document.querySelector(".connection-menu-button").click()')
    await js('document.querySelector("[data-connection-option=sqlite]").click()')
    await create()
    assert.equal(await js('document.querySelectorAll(".connection-row").length'), 3)
    assert.equal(await js('document.querySelector(".statusbar").textContent.includes("正在执行")'), false)
    connections = JSON.parse(readFileSync(join(directory, 'connections.json'), 'utf8'))
    assert.equal(connections.length, 3)
    console.log('PASS: UI retry and file-dialog cancellation')
  } catch (error) {
    console.error(error)
    exitCode = 1
  } finally {
    app.emit('before-quit', { preventDefault() {} })
    rmSync(directory, { recursive: true, force: true })
    app.exit(exitCode)
  }
})
